import requests
import csv
import os

APP_IDS = {
    "Math Fact Master": "389801252",
    "Matharoo Flashcards": "123456789" # 换成你查到的app id
}
OUTPUT_CSV = "appstore_reviews.csv"
OUTPUT_BRIEF = "brief_from_reviews.md"

def fetch_appstore_reviews(app_name, app_id, country="us", max_page=3):
    rows = []
    for page in range(1, max_page+1):
        url = f"https://itunes.apple.com/{country}/rss/customerreviews/page={page}/id={app_id}/sortby=mostrecent/json"
        try:
            resp = requests.get(url, timeout=15)
            data = resp.json()
            entries = data.get("feed", {}).get("entry", [])
            for entry in entries:
                rating = entry.get("im:rating", {}).get("label", "")
                title = entry.get("title", {}).get("label", "")
                content = entry.get("content", {}).get("label", "")
                author = entry.get("author", {}).get("name", {}).get("label", "")
                if int(rating) <=3: # 只抓差评（痛点）
                    rows.append({
                        "app": app_name,
                        "rating": rating,
                        "title": title,
                        "content": content,
                        "author": author
                    })
        except Exception as e:
            print(f"fetch {app_name} page {page} err: {e}")
    return rows

all_reviews = []
for name, aid in APP_IDS.items():
    all_reviews.extend(fetch_appstore_reviews(name, aid))

# 保存csv
with open(OUTPUT_CSV, "w", newline="", encoding="utf-8") as f:
    w = csv.DictWriter(f, fieldnames=["app","rating","title","content","author"])
    w.writeheader()
    w.writerows(all_reviews)

# 生成 brief.md 给 replica-skill
md = """
# User Pain Points from App Store Reviews (Homeschool Math Fact App)
> Auto generated by scraper, feed to /replica-recon
Target: US K1-K5 math drill / flashcard app, Flutter Android+iOS, COPPA/GDPR compliant

## Raw negative feedback
"""
for r in all_reviews:
    md += f"- [{r['app']}] ⭐{r['rating']} | {r['title']}\n  {r['content']}\n\n"

md += """
## Core requirement summary (for architect)
- Offline first, no mandatory login
- Support custom fact set selection (7,8,9 multiplication only)
- Custom numeric keyboard, not only multiple choice
- Toggle timer (disable for math anxiety / dyscalculia kids)
- Multi child profiles, separate progress
- PDF worksheet & printable certificate export
- Smart review of incorrect facts
- Prefer one-time purchase over subscription
- No heavy gamification, no loud distracting ads
"""
with open(OUTPUT_BRIEF, "w", encoding="utf-8") as f:
    f.write(md)

print(f"Done. Saved {len(all_reviews)} negative reviews to {OUTPUT_CSV}, brief -> {OUTPUT_BRIEF}")
